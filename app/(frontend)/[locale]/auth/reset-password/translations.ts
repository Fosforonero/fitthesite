import type { ResetPasswordTranslations } from './ResetPasswordForm';

// Le uniche locale realmente generate da `redirectTo` lato app sono quelle
// che `siteLocaleFor()` (AppFitmesh/flutter_app/lib/core/config/site_locale.dart)
// puo' produrre: la stessa "vista" gia' usata da app/.../auth/callback/route.ts
// (locali del sito meno quelle a contenuto non tradotto). Non e' un elenco
// hardcoded indipendente: e' derivato da lib/i18n.ts.
// TS non stringe il tipo di ritorno di `.filter()` in base al predicato: a
// livello di TIPI dobbiamo escludere esplicitamente le stesse 4 locale di
// `UNTRANSLATED_CONTENT_LOCALES`. Il test "has exactly the 11 canonical..."
// in translations.test.ts verifica a runtime che l'array filtrato sotto
// coincida davvero con questo tipo, cosi' se `UNTRANSLATED_CONTENT_LOCALES`
// cambia in lib/i18n.ts senza aggiornare qui, il test rosso lo segnala.
//
// Vive in un modulo separato da page.tsx (non semplice refactor stilistico):
// Next.js valida gli export di un file page.tsx contro un allowlist fissa
// (default export + generateMetadata/generateStaticParams/dynamic/...) e
// rifiuta il build production ("X is not a valid Page export field") per
// qualunque altro named export, anche se tsc --noEmit da solo non lo segnala.
